"""Build demo7 independently, reusing the tested domain and map sources of demo6."""
from pathlib import Path
import hashlib
import json

DEMO = Path(__file__).resolve().parents[1] / 'demo'

def main():
    config = json.loads((DEMO / 'build.demo7.config.json').read_text(encoding='utf-8'))
    sources = {}
    def read(name):
        path = (DEMO / name).resolve()
        if not path.is_relative_to(DEMO.resolve()):
            raise ValueError('Source outside demo')
        sources[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        return path.read_text(encoding='utf-8')
    analytics = read(config['analytics'])
    markdown = (DEMO.parents[1] / config['state_plan_markdown']).read_text(encoding='utf-8')
    sources[config['state_plan_markdown']] = hashlib.sha256(markdown.encode()).hexdigest()
    js = "/* Generated by construir_demo7.py */\n(() => {\n'use strict';\nconst analyticsModule={exports:{}};\n(function(module){\n"
    js += analytics + '\n})(analyticsModule);\nconst UmbralAnalytics=analyticsModule.exports;\n'
    js += 'const statePlanMarkdown=' + json.dumps(markdown, ensure_ascii=False) + ';\n'
    js += '\n'.join('/* SOURCE: '+name+' */\n'+read(name) for name in config['scripts'])
    js += '\n})();\n'
    css = '\n'.join('/* SOURCE: '+name+' */\n'+read(name) for name in config['styles'])
    for name, content in [('demo7.js', js), ('demo7.css', css)]:
        (DEMO / 'assets' / name).write_text(content, encoding='utf-8')
    (DEMO / 'assets' / 'build.demo7.json').write_text(json.dumps({'sources':sources, 'outputs':{name:hashlib.sha256((DEMO/'assets'/name).read_bytes()).hexdigest() for name in ['demo7.js','demo7.css']}}, indent=2)+'\n', encoding='utf-8', newline='\n')
    print('Demo7: assets/demo7.js and assets/demo7.css generated.')

if __name__ == '__main__':
    main()
